// Helper functions
export function getProductById(id: string): Product | undefined {
  return products.find((p) => p.id === id);
}

export function getProductsByCategory(category: Category): Product[] {
  return products.filter((p) => p.category === category);
}

export function getFeaturedProducts(): Product[] {
  return products.filter((p) => p.featured && p.availability);
}

export function getAvailableProducts(): Product[] {
  return products.filter((p) => p.availability);
}

export function getComplementaryProducts(productId: string): Product[] {
  const product = getProductById(productId);
  if (!product) return [];
  return product.complementaryProducts
    .map((id) => getProductById(id))
    .filter((p): p is Product => p !== undefined && p.availability);
}

export function searchProducts(query: string): Product[] {
  const q = query.toLowerCase();
  return products.filter(
    (p) =>
      p.availability &&
      (p.name.toLowerCase().includes(q) ||
        p.description.toLowerCase().includes(q) ||
        p.tags.some((t) => t.includes(q)) ||
        p.suitableConcerns.some((c) => c.includes(q)) ||
        p.category.toLowerCase().includes(q))
  );
}
